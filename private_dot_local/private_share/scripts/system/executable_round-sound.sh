# -----------------------------------------------------------------------------------------------------------------------------------------
# Simply round the sound to the nearest multiple of 5.
# -----------------------------------------------------------------------------------------------------------------------------------------

vol=$(wpctl get-volume @DEFAULT_AUDIO_SINK@ | grep -oP '\d+\.\d+')
rounded=$(awk -v v="$vol" 'BEGIN{printf "%d", int((v*100+2.5)/5)*5}')
wpctl set-volume @DEFAULT_AUDIO_SINK@ "${rounded}%"
