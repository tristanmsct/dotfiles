# -----------------------------------------------------------------------------------------------------------------------------------------
new_value=$1

if [ "$new_value" = "mute" ]; then
    wpctl set-mute @DEFAULT_SINK@ toggle
else
    wpctl set-volume @DEFAULT_SINK@ "$new_value%"
fi
