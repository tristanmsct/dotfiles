if hyprctl monitors -j | jq -e 'any(.[]; .name == "eDP-1")'; then
    sed -i -E 's/^([$]input_screen_target =) .*$/\1 eDP-1/' "$XDG_CONFIG_HOME/hypr/conf/colors-hyprlock.conf"
else
    monitor_name=$(hyprctl monitors -j | jq -r '.[0].name')
    sed -i -E "s/^([$]input_screen_target =) .*$/\1 $monitor_name/" "$XDG_CONFIG_HOME/hypr/conf/colors-hyprlock.conf"
fi
