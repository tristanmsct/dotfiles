VPN_STATUS_FILE=$HOME/.cache/vpnstatus
INTERFACE=$(ip link show type wireguard up | awk -F': ' '{print $2}' | cut -d'@' -f1)

touch $VPN_STATUS_FILE

if [[ $INTERFACE == "" ]]; then
    echo "VPN Down" > $VPN_STATUS_FILE
else
    echo "VPN Up > $INTERFACE" > $VPN_STATUS_FILE
fi
